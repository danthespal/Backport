"""Generate ps5bp/candidates.py from AnyPS5's "Silent stubs" (docs/dev/TechnicalDebt.md).

A candidate is a function AnyPS5 implements as a bare `return <constant>;` and lists
as a silent stub, i.e. games are known to survive that result. Candidates are
reference-derived, not console-proven: ps5bp applies them only on request
(--candidate-fixes) and only to imports missing on the target firmware.

Usage (from the repo root):  python tools/gen_candidates.py [ANYPS5_DIR]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from ps5bp.nid import compute_nid  # noqa: E402

ANYPS5 = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '.original', 'reference', 'AnyPS5')
PRX = os.path.join(ANYPS5, 'core', 'libs', 'prx')
OUT = os.path.join(ROOT, 'ps5bp', 'candidates.py')

FUNC = re.compile(r'(?:APS5_EXPORT\("([A-Za-z0-9+\-]{11})",\s*\w+\);\s*)?'
                  r'[\w:<>\s\*]+?APS5_VABI\s+(\w+)\s*\(([^)]*)\)\s*(?:noexcept\s*)?(?:try\s*)?\{')


def load_constants():
    """NAME -> int from constexpr/#define/enum definitions across AnyPS5."""
    consts = {}
    pat = re.compile(r'(?:constexpr[^=;]*?\b|#define\s+|^\s*)([A-Z][A-Z0-9_]{2,})\s*=?\s*'
                     r'(?:static_cast<[^>]+>\()?\(?\s*(-?0x[0-9A-Fa-f]+|-?\d+)[uUlL]*\)?', re.M)
    for dirpath, _, files in os.walk(os.path.join(ANYPS5, 'core', 'libs')):
        for name in files:
            if name.endswith(('.hpp', '.cpp', '.h')):
                text = open(os.path.join(dirpath, name), encoding='utf-8', errors='replace').read()
                for m in pat.finditer(text):
                    consts.setdefault(m.group(1), int(m.group(2), 0))
    return consts


def body_of(text, brace):
    depth, i = 0, brace
    while i < len(text):
        if text[i] == '{':
            depth += 1
        elif text[i] == '}':
            depth -= 1
            if depth == 0:
                return text[brace + 1:i]
        i += 1
    return ''


def constant_return(body, consts):
    """The returned constant if the body is only `(void)x;` statements plus `return C;`."""
    body = re.sub(r'//[^\n]*|/\*.*?\*/', '', body, flags=re.S)
    stmts = [s.strip() for s in body.split(';') if s.strip()]
    stmts = [s for s in stmts if not re.fullmatch(r'\(void\)\s*\w+', s)]
    if len(stmts) != 1 or not stmts[0].startswith('return'):
        return None
    expr = stmts[0][len('return'):].strip()
    expr = re.sub(r'^static_cast<[^>]+>\((.*)\)$', r'\1', expr).strip()
    if re.fullmatch(r'-?(0x[0-9A-Fa-f]+|\d+)[uUlL]*', expr):
        return int(expr.rstrip('uUlL'), 0)
    return consts.get(expr)


def silent_stub_bullets():
    """[(linked file, named functions)] from the Silent stubs section."""
    text = open(os.path.join(ANYPS5, 'docs', 'dev', 'TechnicalDebt.md'), encoding='utf-8').read()
    section = text.split('### Silent stubs', 1)[1].split('\n### ', 1)[0]
    out = []
    for line in section.splitlines():
        if not line.startswith('- ['):
            continue
        link = re.search(r'\]\(\.\./\.\./core/libs/prx/([^)]+)\)', line)
        if link:
            out.append((link.group(1), set(re.findall(r'`(\w+)`', line))))
    return out


def main():
    consts = load_constants()
    found = {}
    for rel, named in silent_stub_bullets():
        path = os.path.join(PRX, rel)
        if not os.path.isfile(path):
            continue
        text = open(path, encoding='utf-8', errors='replace').read()
        defined = {m.group(2) for m in FUNC.finditer(text)}
        restrict = named & defined          # bullet names specific functions -> only those
        for m in FUNC.finditer(text):
            nid_alias, name = m.group(1), m.group(2)
            if restrict and name not in restrict:
                continue
            value = constant_return(body_of(text, m.end() - 1), consts)
            if value is None:
                continue
            nid = nid_alias or compute_nid(name)
            line = text.count('\n', 0, m.start()) + 1
            found[nid] = (name, value & 0xFFFFFFFF, f'AnyPS5 {rel}:{line}')

    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('"""GENERATED by tools/gen_candidates.py from AnyPS5 docs/dev/TechnicalDebt.md "Silent stubs".\n\n'
                'Reference-derived stub candidates (not console-proven): functions AnyPS5 implements\n'
                'as `return <constant>;` and documents as safe no-ops. Applied only with\n'
                '--candidate-fixes, and only to imports missing on the target firmware.\n'
                'Regenerate instead of editing by hand.\n"""\n\n')
        f.write('# NID: (function name, 32-bit return value, source)\n')
        f.write('CANDIDATES = {\n')
        for nid, (name, value, src) in sorted(found.items(), key=lambda kv: kv[1][0]):
            f.write(f'    {nid!r}: ({name!r}, {value:#010x}, {src!r}),\n')
        f.write('}\n')
    print(f'{len(found)} candidates written to {OUT}')
    for nid, (name, value, src) in sorted(found.items(), key=lambda kv: kv[1][0]):
        print(f'  {nid} {name:48} -> {value:#010x}  ({src})')


if __name__ == '__main__':
    main()
